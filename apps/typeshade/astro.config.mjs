import { copyFileSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'astro/config';
import sitemap from '@astrojs/sitemap';
import tailwindcss from '@tailwindcss/vite';
import expressiveCode from 'astro-expressive-code';
import remarkMath from 'remark-math';
import rehypeMath from './src/lib/rehype-math.mjs';
import remarkApiLinks from './src/lib/remark-api-links.mjs';
import remarkDocTables from './src/lib/remark-doc-tables.mjs';
import remarkErrorLinks from './src/lib/remark-error-links.mjs';
import remarkPackageName from './src/lib/remark-package-name.mjs';
import remarkPromoteBoldLeads from './src/lib/remark-promote-bold-leads.mjs';
import remarkRuleLinks from './src/lib/remark-rule-links.mjs';
import { verifyArtifacts } from './scripts/artifacts.mjs';
import { retiredExampleRedirects } from './src/lib/retired-examples.mjs';
import { retiredGuideRedirects } from './src/lib/retired-guide-sections.mjs';
import { verifyKoreanFonts } from './scripts/fonts.mjs';
import { playgroundHostTypes } from './scripts/playground-host-types.mjs';

const root = fileURLToPath(new URL('.', import.meta.url));
const retiredPaths = new Set([
  ...Object.keys(retiredExampleRedirects()),
  ...Object.keys(retiredGuideRedirects()),
]);

// typeshade.dev: a static site built from the compiler vendored at vendor/shader-dsl. Every
// code sample and number on the page is computed from that checkout at build time.
export default defineConfig({
  site: 'https://typeshade.dev',
  output: 'static',
  trailingSlash: 'always',
  // The docs moved under /guide/ on the day the site launched; the first routes redirect. The
  // pages of the `fn()` registry examples redirect to their source twins, or to the examples
  // page where there is none (src/lib/retired-examples.mjs). A guide section the compiler's
  // AUTHORING.md removed redirects to the page that holds what it said
  // (src/lib/retired-guide-sections.mjs).
  redirects: Object.fromEntries(
    Object.entries({
      '/motivation/': '/guide/introduction/',
      '/checks/': '/guide/checks/',
      '/examples/': '/guide/examples/',
      '/guide/': '/guide/introduction/',
      ...retiredExampleRedirects(),
      ...retiredGuideRedirects(),
    }).flatMap(([from, to]) => [
      [from, to],
      [`/ko${from}`, `/ko${to}`],
    ]),
  ),
  // English at /, every other locale under its own prefix. The copy lives in src/i18n.
  i18n: { defaultLocale: 'en', locales: ['en', 'ko'], routing: { prefixDefaultLocale: false } },
  integrations: [
    // og.png, the icons and the canvas stills are generated by scripts and committed with a
    // .sha256 each. The build checks the hashes instead of running a browser.
    {
      name: 'typeshade:artifact-hashes',
      hooks: {
        'astro:build:start': () => {
          verifyArtifacts(root);
          verifyKoreanFonts(root);
        },
      },
    },
    // /og/ exists only so capture-og.ts can photograph it, and /capture-stills/ only so
    // capture-stills.ts can; neither is served.
    {
      name: 'typeshade:capture-routes',
      hooks: {
        'astro:build:done': ({ dir }) => {
          if (process.env.OG_REBASELINE !== '1')
            rmSync(fileURLToPath(new URL('og/', dir)), { recursive: true, force: true });
          if (process.env.STILLS_REBASELINE !== '1')
            rmSync(fileURLToPath(new URL('capture-stills/', dir)), {
              recursive: true,
              force: true,
            });
        },
      },
    },
    expressiveCode(), // options in ec.config.mjs
    sitemap({
      filter: (page) =>
        ![
          '/og',
          '/capture-stills',
          '/motivation',
          '/checks',
          '/examples',
          '/guide',
          '/ko/motivation',
          '/ko/checks',
          '/ko/examples',
          '/ko/guide',
          '/ko/404',
          // The template worker/index.ts fills in for an example newer than the build.
          '/guide/examples/runtime-example',
          '/ko/guide/examples/runtime-example',
          // The gallery's template, which worker/gallery.ts serves at gallery.typeshade.dev.
          '/gallery',
          '/ko/gallery',
        ].includes(new URL(page).pathname.replace(/\/$/, '')) &&
        // The retired example pages and guide sections only redirect
        // (src/lib/retired-examples.mjs, src/lib/retired-guide-sections.mjs).
        !retiredPaths.has(new URL(page).pathname.replace(/^\/ko(?=\/)/, '')) &&
        // /guide/authoring/ and its sections only redirect to /guide/internals/.
        !/^\/(ko\/)?guide\/authoring\//.test(new URL(page).pathname),
      // No lastmod: one build date on every URL tells a crawler nothing, and Google stops
      // reading a sitemap's lastmod once it proves inaccurate.
      i18n: { defaultLocale: 'en', locales: { en: 'en', ko: 'ko' } },
    }),
    // Astro writes each redirect above as an HTML page with a refresh, noindex and a canonical
    // link, which a crawler reports as a page it cannot index. dist/_redirects gives Workers
    // static assets the same routes as permanent redirects (docs/cloudflare.md), read off the
    // pages Astro wrote, so a route added any other way is covered too.
    {
      name: 'typeshade:permanent-redirects',
      hooks: {
        'astro:build:done': ({ dir }) => {
          const out = fileURLToPath(dir);
          const lines = [];
          const walk = (d) => {
            for (const e of readdirSync(d, { withFileTypes: true })) {
              const p = path.join(d, e.name);
              if (e.isDirectory()) walk(p);
              else if (e.name === 'index.html') {
                const m =
                  /^<!doctype html><title>Redirecting to: ([^<]+)<\/title><meta http-equiv="refresh"/.exec(
                    readFileSync(p, 'utf8').slice(0, 400),
                  );
                if (m)
                  lines.push(
                    `/${path.relative(out, path.dirname(p)).split(path.sep).join('/')}/ ${m[1]} 301`,
                  );
              }
            }
          };
          walk(out);
          lines.sort();
          writeFileSync(
            path.join(out, '_redirects'),
            `# Written by astro.config.mjs from the redirect pages the build wrote.\n${lines.join('\n')}\n`,
          );
        },
      },
    },
    // Crawlers and people still ask for /sitemap.xml; serve the index there too.
    {
      name: 'typeshade:sitemap-alias',
      hooks: {
        'astro:build:done': ({ dir }) => {
          copyFileSync(
            fileURLToPath(new URL('sitemap-index.xml', dir)),
            fileURLToPath(new URL('sitemap.xml', dir)),
          );
        },
      },
    },
  ],
  // The package name first, then the guide's first mention of each export as a link to its
  // reference page, and the first mention of each error code and each design rule as a link to
  // its page.
  markdown: {
    remarkPlugins: [
      remarkPackageName,
      remarkPromoteBoldLeads,
      remarkDocTables,
      remarkApiLinks,
      remarkErrorLinks,
      remarkRuleLinks,
      // Formulas in LaTeX, `$…$` and `$$…$$`, rendered to MathML by rehypeMath (src/lib/math.mjs).
      remarkMath,
    ],
    rehypePlugins: [rehypeMath],
  },
  // The declarations the Playground's host.ts is type-checked against, one asset the language
  // worker fetches when host.ts is first opened (scripts/playground-host-types.mjs).
  // A worker script is one IIFE file. The Playground's host frame loads the runtime as such a
  // script (src/scripts/playground-host-run.ts), and the runtime loads its WebGL2 half with a
  // dynamic import, inlined here, since the frame cannot load a chunk split off the script.
  // One TypeScript in the language worker: the compiler's and the one host.ts is checked with
  // (src/scripts/playground-host-service.ts). A checkout with the compiler's own dependencies
  // installed would otherwise bundle a second copy from vendor/shader-dsl/node_modules; CI
  // installs none there, so this is the copy CI builds with.
  vite: {
    plugins: [tailwindcss(), playgroundHostTypes(root)],
    resolve: { dedupe: ['typescript'] },
    worker: { rollupOptions: { output: { inlineDynamicImports: true } } },
  },
});
