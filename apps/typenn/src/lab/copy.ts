  const translations: Record<string, readonly string[]> = {
    imdb: ["부정", "긍정"],
    fashion_mnist: ["티셔츠/상의", "바지", "풀오버", "드레스", "코트", "샌들", "셔츠", "운동화", "가방", "앵클 부츠"],
  };
